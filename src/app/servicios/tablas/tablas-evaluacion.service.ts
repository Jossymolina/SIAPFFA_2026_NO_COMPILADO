  sacar_factor_abdomen_cuello(diferencia: number | string): number {
    if (diferencia === null || diferencia === undefined || diferencia === '') {
      throw new Error('La diferencia es obligatoria.');
    }

    const valor = Number(diferencia);
    if (isNaN(valor)) {
      throw new Error(`La diferencia "${diferencia}" no es un número válido.`);
    }
    // Parte entera
    const entero = Math.trunc(valor);
    // Parte decimal (0-99)
    let decimales = 0;
    const partes = valor.toString().split('.');
    if (partes.length > 1) {
      // Toma solo los dos primeros decimales
      decimales = Number(partes[1].substring(0, 2).padEnd(2, '0'));
      if (isNaN(decimales)) {
        decimales = 0;
      }
    }



    const fila = this.arreglo_factor_abdomen_cuello.find(
      item => item.diferencia === entero
    );

    if (!fila) {
      return 0
      //throw new Error(`No existe una fila para la diferencia ${entero}.`);
    }

    if (!Array.isArray(fila.fila) || fila.fila.length === 0) {
      throw new Error(`La fila ${entero} no contiene factores.`);
    }

    const factor = fila.fila.find((item, index) => {

      const siguiente = fila.fila[index + 1];

      if (!siguiente) {
        return decimales >= item.rango;
      }


      return decimales >= item.rango && decimales < siguiente.rango;
    });

    if (!factor) {
      throw new Error(
        `No existe un factor para la diferencia ${valor} (decimal ${decimales}).`
      );
    }

    return factor.factor;
  }


